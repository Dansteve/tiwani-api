def invite_viewer(
    user: AuthedUser,
    *,
    recipient_id: str,
    email: str,
    role: ShareRole = ShareRole.VIEWER,
    subject_kind: SubjectKind = SubjectKind.CHILD,
) -> InviteCreated:
    """Invite someone to see one of the caller's recipients' Continuity Card (owner only).

    Steps:
      1. verify the caller OWNS the recipient (RLS-scoped). Not owned -> 404.
      2. build the GOVERNED consent text for this recipient + subject kind (the api owns
         the wording; the client never authors consent copy).
      3. generate the opaque email-bound token (secrets.token_urlsafe) AND a short typable
         JOIN CODE (Crockford base32, 10 chars / ~50 bits, a CSPRNG; the 2026-06-13 board
         verdict), so a helper can TYPE the code instead of pasting the long token.
      4. call the code-aware share_recipient_invite (SECURITY DEFINER) with the 48h code TTL:
         for a CHILD it records the consent atomically THEN mints (carrying both the token
         and the normalized code); for an ADULT it mints ONLY if a recorded adult consent
         already exists, else it raises (-> AdultConsentRequiredError -> 409). A (vanishingly
         rare) active-code collision the DB partial-unique index rejects is retried with a
         fresh code.
      5. return the invite id + token + the FORMATTED join code (XXXXX-XXXXX) + its governed
         "private code" copy_key + expiry + the governed invite copy_key + the recorded
         consent_text, so the app builds the share link, shows the typable code, and the warm
         invite line.

    The expiry is computed by the RPC (now() + 48h for the code-bearing share); we read the
    minted invite back under RLS (the owner can select their recipient's invites) to return
    the canonical expires_at, so the app shows the true link/code lifetime.
    """
    owned = _require_owned_recipient(user, recipient_id)
    first_name = _first_name(owned.get("name"))

    consent_text = sharing_copy.consent_text(first_name, subject_kind=subject_kind.value)
    consent_text_arg = consent_text if subject_kind == SubjectKind.CHILD else None

    token = secrets.token_urlsafe(INVITE_TOKEN_BYTES)

    client = get_anon_client(user.access_token)

    # Mint the invite carrying BOTH the opaque token and the short typable join code, via the
    # code-aware share_recipient_invite (consent stays gated + atomic). A (vanishingly rare)
    # active-code collision the DB partial-unique index rejects is retried with a fresh code.
    invite_id = None
    normalized_code = ""
    last_exc: Optional[Exception] = None
    for _ in range(JOIN_CODE_MINT_RETRIES):
        normalized_code = join_code_helper.generate_join_code()
        try:
            response = client.rpc(
                SHARE_INVITE_FN,
                {
                    "p_child_id": recipient_id,
                    "p_email": email,
                    "p_role": role.value,
                    "p_token": token,
                    "p_subject_kind": subject_kind.value,
                    "p_consent_text": consent_text_arg,
                    "p_ttl_hours": JOIN_CODE_TTL_HOURS,
                    "p_join_code": normalized_code,
                },
            ).execute()
        except Exception as exc:  # noqa: BLE001
            # The adult-block RPC raises P0001 "adult recipient sharing requires recorded
            # consent first"; surface it as the typed AdultConsentRequiredError (the route
            # maps it to the calm 409).
            if _is_adult_consent_block(exc):
                raise AdultConsentRequiredError(
                    "Adult recipient sharing requires recorded consent first"
                ) from exc
            # A duplicate active join_code (the partial unique index) is a transient
            # collision: remember it and retry with a fresh code. Any other RPC failure
            # re-raises immediately (it is not a collision we can retry past).
            if _is_join_code_collision(exc):
                last_exc = exc
                continue
            raise
        invite_id = _rpc_scalar(response)
        break
    if invite_id is None:
        # Exhausted the retries on repeated collisions (astronomically unlikely at 50 bits):
        # surface the last error rather than returning a half-result.
        raise last_exc if last_exc is not None else RuntimeError(
            "could not mint a unique join code"
        )

    invite_row = _read_owned_invite(user, recipient_id, invite_id)
    expires_at = (invite_row or {}).get("expires_at")

    return InviteCreated(
        invite_id=invite_id,
        token=token,
        join_code=join_code_helper.format_join_code(normalized_code),
        join_code_copy_key=sharing_copy.JOIN_CODE_COPY_KEY,
        role=role,
        expires_at=expires_at,
        copy_key=sharing_copy.INVITE_COPY_KEY,
        consent_text=consent_text,
    )


def record_adult_consent(user: AuthedUser, *, recipient_id: str) -> ConsentRecorded:
    """Record an ADULT recipient's own consent so a later adult share is unblocked.

    The adult-share precondition (refinement 5). Verifies ownership (the owning Coordinator
    records it on the adult's behalf at the adult's direction; the app gates this on the
    adult's confirmation), builds the governed adult consent text, and calls
    record_share_consent (SECURITY DEFINER, owner-checked). Returns the consent id + the
    governed copy. After this, invite_viewer(..., subject_kind=adult) for the recipient
    will mint.
    """
    owned = _require_owned_recipient(user, recipient_id)
    first_name = _first_name(owned.get("name"))
    consent_text = sharing_copy.consent_text(first_name, subject_kind=SubjectKind.ADULT.value)

    client = get_anon_client(user.access_token)
    response = client.rpc(
        RECORD_CONSENT_FN,
        {
            "p_child_id": recipient_id,
            "p_subject_kind": SubjectKind.ADULT.value,
            "p_consent_text": consent_text,
        },
    ).execute()
    consent_id = _rpc_scalar(response)

    return ConsentRecorded(
        consent_id=consent_id,
        copy_key=sharing_copy.consent_copy_key(SubjectKind.ADULT.value),
        consent_text=consent_text,
    )


