def redeem_invite(user: AuthedUser, *, token: str) -> RedeemResult:
    """Redeem an invite TOKEN; return which recipient was linked + the governed copy.

    Calls redeem_recipient_invite (SECURITY DEFINER, atomic, email-bound, first-wins) to get
    the new membership id, then funnels into the SHARED _redeem_result_from_membership_id
    read-back (the same path the by-code redeem uses). A bad token (unknown / expired / used
    / revoked / wrong email) raises -> InviteRedeemError (the route maps to a friendly 4xx).
    """
    client = get_anon_client(user.access_token)
    try:
        response = client.rpc(REDEEM_INVITE_FN, {"p_token": token}).execute()
    except Exception as exc:  # noqa: BLE001
        raise InviteRedeemError(str(exc)) from exc
    return _redeem_result_from_membership_id(user, _rpc_scalar(response))


def redeem_invite_by_code(user: AuthedUser, *, join_code: str) -> RedeemResult:
    """Redeem an invite by the short typable JOIN CODE (the 2026-06-13 board verdict).

    Normalizes the typed code (case- and dash-insensitive, the Crockford input aliases
    I/L -> 1, O -> 0 forgiven; app/engines/sharing/join_code.py), then calls
    redeem_recipient_invite_by_code (SECURITY DEFINER, atomic, email-bound, first-wins) and
    funnels into the SAME _redeem_result_from_membership_id read-back the token path uses
    (it does NOT duplicate the membership-creation or result logic).

    NO-ORACLE: a malformed code (normalization fails) and an unresolvable / expired / used /
    revoked / wrong-email code BOTH raise InviteRedeemError, which the route maps to ONE
    generic 400 with an identical body. The by-code RPC itself raises ONE uniform error for
    every failure reason, so neither this layer nor the route can tell "no such code" from
    "code exists but you are not the bound email". The email-bind (enforced inside the RPC)
    is the real second factor: a guessed code is useless unless the caller is signed in as
    the invite's bound email.
    """
    try:
        normalized = join_code_helper.normalize_join_code(join_code)
    except join_code_helper.InvalidJoinCodeError as exc:
        # A malformed code is the SAME generic failure as an unknown one (no oracle): we do
        # not even reach the RPC, and the route returns the identical 400.
        raise InviteRedeemError("Invite could not be redeemed") from exc

    client = get_anon_client(user.access_token)
    try:
        response = client.rpc(REDEEM_BY_CODE_FN, {"p_join_code": normalized}).execute()
    except Exception as exc:  # noqa: BLE001
        raise InviteRedeemError(str(exc)) from exc
    return _redeem_result_from_membership_id(user, _rpc_scalar(response))


def _redeem_result_from_membership_id(
    user: AuthedUser, membership_id: Any
) -> RedeemResult:
    """The SHARED post-redeem read-back, reached by BOTH the token and the by-code path.

    Given the membership id the redeem RPC returned, read the membership back under RLS (the
    now-active member can select the roster of that recipient) to learn the recipient_id and
    the role, read the recipient's FIRST name through the capped member card path (so a
    viewer never learns more than the first name), and build the RedeemResult with the
    governed linked-state copy. A missing id or an unreadable membership is a redeem failure
    (InviteRedeemError) rather than a half-result. This is the ONE place the membership ->
    result mapping lives, so the token and code paths cannot drift.
    """
    if not membership_id:
        raise InviteRedeemError("Invite could not be redeemed")

    membership = _read_membership_by_id(user, membership_id)
    if membership is None:
        # The membership exists (the RPC returned its id) but the read-back found nothing;
        # treat as a redeem failure rather than returning a half-result.
        raise InviteRedeemError("Invite redeemed but membership is not readable")

    recipient_id = membership["recipient_id"]
    role = _safe_role(membership.get("role"))
    first_name = _shared_recipient_first_name(user, recipient_id)

    return RedeemResult(
        recipient_id=recipient_id,
        recipient_first_name=first_name,
        role=role,
        copy_key=sharing_copy.LINKED_COPY_KEY,
    )


